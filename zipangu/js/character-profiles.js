export function characterArc(profile, id, person, live) {
    const active = person.requests.find(r => r.status === 'active');
    const queued = person.requests.find(r => r.status === 'queued');
    const stage = person.trust >= 5 && live.milestone >= 1 ? 3 : person.trust >= 3 || person.practice >= 3 ? 2 : person.trust > 0 ? 1 : 0;
    const chapters = ['出会いの頁', '初めて結んだ約束', '記録を重ねる道', '願いへの小さな一歩'];
    let feeling = profile.mood;
    if (active) feeling = `あなたとの「${active.title}」に向かいながら、${profile.mood}`;
    else if (queued) feeling = `先の仕事を終えたら、あなたとの約束へ。${profile.mood}`;
    else if (live.needs.fatigue > 0.75) feeling = `歩みを少しゆるめる。${profile.mood}`;
    else if (person.trust > 0) feeling = `果たした約束を覚えている。${profile.mood}`;
    else if (person.practice > 0) feeling = `細工や記録を重ねている。${profile.mood}`;
    const recent = person.memories.at(-1);
    const next = stage > 0 ? NEXT_STEPS[id] : profile.wish;
    return { stage, chapter: chapters[stage], feeling, next,
        narrative: stage === 0 ? 'まだ始まったばかりの縁。言葉の先で、一緒に残せる記録を待っています。'
            : stage === 1 ? '初めての約束が、実際に辿り着いた場所の記憶になりました。'
                : stage === 2 ? '細工や現地の記録を重ねています。変わったのは数字だけでなく、帳に残る行き先です。'
                    : '一緒に果たした約束と、本人の経済目標の節目が重なりました。大きな願いは、まだこの先へ。', recent };
}
