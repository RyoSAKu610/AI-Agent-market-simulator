#!/usr/bin/env node
// Compiles contracts/Kogane.sol into js/kogane.js (the ABI and the bytecode the page deploys on
// the EVM test networks; docs/ONCHAIN.md).
//
//   node tools/kogane-build.mjs --solc <path to the solc npm package>   regenerate js/kogane.js
//   node tools/kogane-build.mjs --check                                 is js/kogane.js built from this source?
//
// The repository has no package.json, so solc is whatever the maintainer points --solc (or the
// SOLC_JS environment variable) at, e.g. a scratch `npm install solc@0.8.28`. The pinned settings
// below and `bytecodeHash: none` make the output reproducible from the source alone.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = join(root, 'contracts', 'Kogane.sol');
const OUT = join(root, 'js', 'kogane.js');
const VERSION = '0.8.28';
const SETTINGS = { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', metadata: { bytecodeHash: 'none' }, outputSelection: { '*': { Kogane: ['abi', 'evm.bytecode.object'] } } };

const source = readFileSync(SOURCE, 'utf8');
const sourceHash = createHash('sha256').update(source).digest('hex');
const argv = process.argv.slice(2);
const opt = name => { const i = argv.indexOf('--' + name); return i < 0 ? null : argv[i + 1]; };

if (argv.includes('--check')) {
    const built = readFileSync(OUT, 'utf8');
    const m = /KOGANE_SOURCE_SHA256 = '([0-9a-f]{64})'/.exec(built);
    if (!m || m[1] !== sourceHash) {
        console.error(`js/kogane.js was not built from contracts/Kogane.sol (source ${sourceHash.slice(0, 12)}…). Run: node tools/kogane-build.mjs --solc <solc package>`);
        process.exit(1);
    }
    console.log('kogane.js matches contracts/Kogane.sol');
    process.exit(0);
}

const solcPath = opt('solc') || process.env.SOLC_JS;
if (!solcPath) { console.error('usage: node tools/kogane-build.mjs --solc <path to node_modules/solc>  (or --check)'); process.exit(2); }
const solc = createRequire(import.meta.url)(resolve(solcPath));
if (!String(solc.version()).startsWith(VERSION)) { console.error(`need solc ${VERSION}, got ${solc.version()}`); process.exit(2); }
const out = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources: { 'Kogane.sol': { content: source } }, settings: SETTINGS })));
const errors = (out.errors || []).filter(e => e.severity === 'error');
if (errors.length) { for (const e of errors) console.error(e.formattedMessage); process.exit(1); }
const c = out.contracts['Kogane.sol'].Kogane;
const bytecode = '0x' + c.evm.bytecode.object;

writeFileSync(OUT, `// Generated by tools/kogane-build.mjs from contracts/Kogane.sol. Do not edit by hand.
// solc ${solc.version()}, optimizer 200 runs, EVM paris, no metadata hash.
// The KOGANE token the EVM engine (js/chain-evm.js) deploys on Robinhood Chain Testnet and Arc Testnet.

export const KOGANE_SOURCE_SHA256 = '${sourceHash}';
export const KOGANE_ABI = ${JSON.stringify(c.abi)};
export const KOGANE_BYTECODE = '${bytecode}';
`);
console.log(`js/kogane.js: ${(bytecode.length - 2) / 2} bytes of bytecode, source ${sourceHash.slice(0, 12)}…`);
