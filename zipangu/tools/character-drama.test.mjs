import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildWorld } from '../js/data.js';
import { createEconomy } from '../js/sim.js';
import { createStories } from '../js/character-stories.js';
import { createDrama, DRAMA_VOICES, encounterLines, dramaReadSeconds, dramaAdvance, dramaChoose } from '../js/character-drama.js';
import { validateJourney } from '../js/journey-save.js';
const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'world'), raw = {};
for (const stem of ['world', 'eras', 'realms', 'districts', 'creatures', 'goods', 'currencies', 'agents', 'events', 'library']) raw[stem] = JSON.parse(readFileSync(join(root, stem + '.json')));
const W = buildWorld(raw), eco = createEconomy(W, { seed: 421 });
eco.step(150);
const stories = createStories(W, eco), drama = stories.drama;
assert.deepEqual(new Set(Object.keys(DRAMA_VOICES)), new Set(W.agents.map(a => a.id)));
assert.equal(new Set(Object.values(DRAMA_VOICES).map(v => v[0])).size, 32, 'distinct unfinished questions');
for (const a of W.agents) {
    const s = drama.current(a.id);
    assert.equal(s.cast.length, 1, 'current snapshot does not invent a visitor');
    assert.ok(s.lines.every(l => l.speaker === null || l.speaker === a.id));
    const b = W.agents.find(b => b.id !== a.id);
    const lines = encounterLines(W, a.id, b.id, a.relationships.find(r => r.agent === b.id)?.type);
    assert.ok(lines.some(l => l.speaker === a.id) && lines.some(l => l.speaker === b.id));
}
const first = eco.agents.get('oracle'), other = eco.agents.get('eyevoid');
const fake = { type: 'encounter', seq: 9999, agent: first.id, other: other.id, district: first.home, T: eco.time, day: eco.clock.day, label: eco.clock.label, message: 'not evidence' };
// Use isolated model; remote, in-transit or unrelated arrival evidence is rejected.
const isolated = createDrama(W, eco);
assert.equal(isolated.record({ ...fake, district: 'no-such-place' }), null);
const old = { at: other.at, trip: other.trip };
other.at = null;
assert.equal(isolated.record(fake), null);
other.at = first.home; other.trip = { to: first.home };
assert.equal(isolated.record(fake), null);
Object.assign(other, old);
let meeting;
eco.on('encounter', e => {
    const a = eco.agents.get(e.agent), b = eco.agents.get(e.other);
    assert.equal(a.at, e.district); assert.equal(b.at, e.district);
    assert.equal(a.trip, null); assert.equal(b.trip, null);
    meeting ||= e;
});
for (let i = 0; i < 300 && !meeting; i++) eco.step(1);
assert.ok(meeting, 'actual engine arrival produced co-location');
const s = drama.scenes(meeting.agent).find(s => s.id === `event:${meeting.seq}`);
assert.ok(s && s.cast.includes(meeting.other));
assert.deepEqual(drama.scenes(meeting.other).find(x => x.id === s.id), s, 'both people share one actual scene');
const before = JSON.stringify(stories.snapshot()), wallets = [...eco.agents.values()].map(a => [a.wallet, a.carrying]);
stories.handleEvent(meeting);
assert.equal(JSON.stringify(stories.snapshot()), before, 'duplicate does not create another scene/chronicle or reward');
assert.deepEqual([...eco.agents.values()].map(a => [a.wallet, a.carrying]), wallets);
const reader = drama.reader(meeting.agent); reader.scene = s.id; reader.held = s; reader.beat = 2; reader.auto = false;
for (let i = 0; i < 500; i++) eco.step(1);
assert.ok(drama.snapshot().scenes.length <= 96);
assert.ok(drama.scenes(meeting.agent).length <= 12);
assert.equal(reader.held.id, s.id, 'fast sim cannot throw away the scene being read');
const save = { v: 1, seed: 421, economy: eco.snapshot(), stories: stories.snapshot() };
validateJourney(save, W, 421);
const restored = createEconomy(W, { seed: 421, state: save.economy });
const restoredStories = createStories(W, restored, save.stories);
assert.deepEqual(restoredStories.drama.reader(meeting.agent), reader, 'same scene, utterance and pause survive reload');
assert.deepEqual(restoredStories.drama.reader(meeting.agent).held, s);
dramaChoose(drama.current(meeting.agent), reader);
validateJourney({ ...save, stories: stories.snapshot() }, W, 421); // immediate selection save is coherent
dramaChoose(s, reader); reader.beat = 2;
for (let i = 0; i < 50; i++) { eco.step(1); restored.step(1); }
assert.deepEqual(eco.snapshot(), restored.snapshot(), 'encounter cooldown deterministic after resume');
assert.deepEqual(stories.snapshot(), restoredStories.snapshot());
const legacy = structuredClone(save); delete legacy.stories.drama; delete legacy.economy.encounters;
validateJourney(legacy, W, 421);
assert.equal(createStories(W, createEconomy(W, { seed: 421, state: legacy.economy }), legacy.stories).drama.scenes('zero').length, 0);
const malformed = structuredClone(save); malformed.stories.drama.readers[meeting.agent].held.cast = ['nonexistent'];
assert.throws(() => validateJourney(malformed, W, 421));
const lines = encounterLines(W, 'kane', 'hakuuchi');
assert.match(lines[0].text, /光を手元/); assert.match(lines[1].text, /溜めた光/); assert.match(lines[2].text, /順番/);
assert.ok(dramaReadSeconds('短い一言') >= 5 && dramaReadSeconds('長い'.repeat(100)) <= 13);
const r = { beat: 0 }; assert.ok(dramaAdvance(s, r));
r.beat = s.lines.length - 1; assert.equal(dramaAdvance(s, r), false, 'last line waits for next scene');
console.log('Drama: 32 voices, actual co-location/events, no reward, bounded archive, held reading, legacy/duplicate/save and deterministic resume passed.');
